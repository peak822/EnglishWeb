// 4. Syllabification Engine (English Syllables)
function splitIntoSyllables(word) {
  const w = word.toLowerCase().trim();
  if (w.length <= 3) return [w];

  // Common prefix splitting
  const prefixRegex = /^(anti|auto|bio|co|counter|de|dis|inter|intra|micro|multi|non|over|post|pre|pro|re|semi|sub|super|tele|trans|un|under)/;
  const suffixRegex = /(tion|sion|ment|able|ible|ness|ship|less|ful|ing|ology|graphy|ism|ist|ity|ous|ious|ical|ize|ise)$/;

  let parts = [];
  let remaining = w;

  const preMatch = remaining.match(prefixRegex);
  if (preMatch && remaining.length > preMatch[1].length + 2) {
    parts.push(preMatch[1]);
    remaining = remaining.slice(preMatch[1].length);
  }

  let suffix = '';
  const sufMatch = remaining.match(suffixRegex);
  if (sufMatch && remaining.length > sufMatch[1].length + 2) {
    suffix = sufMatch[1];
    remaining = remaining.slice(0, remaining.length - sufMatch[1].length);
  }

  // Syllabify core word using vowel-consonant heuristic
  const vowels = 'aeiouy';
  let cur = '';
  let coreParts = [];

  for (let i = 0; i < remaining.length; i++) {
    const char = remaining[i];
    cur += char;

    const next1 = remaining[i + 1];
    const next2 = remaining[i + 2];

    const isVowel = vowels.includes(char);
    const isNextVowel = next1 && vowels.includes(next1);
    const isNextNextVowel = next2 && vowels.includes(next2);

    // VCV split -> V-CV
    if (isVowel && next1 && !vowels.includes(next1) && next2 && isNextNextVowel) {
      coreParts.push(cur);
      cur = '';
    }
    // VCCV split -> VC-CV
    else if (isVowel && next1 && !vowels.includes(next1) && next2 && !vowels.includes(next2) && remaining[i + 3] && vowels.includes(remaining[i + 3])) {
      cur += next1;
      i++;
      coreParts.push(cur);
      cur = '';
    }
  }

  if (cur) coreParts.push(cur);
  if (coreParts.length === 0) coreParts.push(remaining);

  parts = [...parts, ...coreParts];
  if (suffix) parts.push(suffix);

  return parts.filter(p => p && p.trim().length > 0);
}

// 5. Thai String Normalizer (fixes consonant/vowel positions)
function normalizeThaiString(str) {
  if (!str) return '';
  let res = str;

  // Fix ordering where front vowels (เ, แ, โ, ใ, ไ) are placed after consonant
  res = res.replace(/([ก-ฮ])([เแโใไ])/g, '$2$1');
  
  // Fix double vowels
  res = res.replace(/แแ/g, 'แ')
           .replace(/เเ/g, 'แ')
           .replace(/ะะ/g, 'ะ')
           .replace(/าา/g, 'า')
           .replace(/ิิ/g, 'ิ')
           .replace(/ีี/g, 'ี')
           .replace(/ึึ/g, 'ึ')
           .replace(/ืื/g, 'ื')
           .replace(/ุุ/g, 'ุ')
           .replace(/ูู/g, 'ู')
           .replace(/่่/g, '่')
           .replace(/้้/g, '้')
           .replace(/๊๊/g, '๊')
           .replace(/๋๋/g, '๋')
           .replace(/์์/g, '์');

  // Fix invalid consonant combinations
  res = res.replace(/อั([ก-ฮ])ด/g, 'แ$1ด');

  return res;
}

// 6. Master Generator Function
function generateThaiPronunciation(word, existingIpa) {
  if (!word || typeof word !== 'string') return '';
  const cleanWord = word.toLowerCase().trim();

  // 1. Exact dictionary match
  if (EXACT_DICTIONARY[cleanWord]) {
    return EXACT_DICTIONARY[cleanWord];
  }
  if (EXACT_DICTIONARY[word]) {
    return EXACT_DICTIONARY[word];
  }

  // 2. Handle hyphenated / space-separated words (e.g. ice cream, well-known)
  if (cleanWord.includes(' ') || cleanWord.includes('-')) {
    const tokens = cleanWord.split(/[\s-]+/);
    const rendered = tokens.map(t => generateThaiPronunciation(t)).filter(Boolean);
    return rendered.join(' ');
  }

  // 3. Decompose into syllables and transcribe
  const syllables = splitIntoSyllables(cleanWord);
  const thaiSyllables = syllables.map((syl, index) => {
    return transliterateEnglishSyllable(syl, index === 0, index === syllables.length - 1, syllables.length);
  });

  let result = thaiSyllables.join('-');
  // Clean up hyphens and formatting
  result = result.replace(/-+/g, '-').replace(/^-+|-+$/g, '').trim();

  // Final fallback if empty
  if (!result) {
    result = 'อะ';
  }

  return result;
}

