// 1. Validation helper
function validatePronunciation(text) {
  if (!text || typeof text !== 'string' || text.trim() === '') {
    return { valid: false, errors: ['Empty pronunciation'] };
  }
  const errors = [];
  if (/[a-zA-Z]/.test(text)) {
    errors.push('Contains Latin characters: ' + text);
  }
  if (text.startsWith('-') || text.endsWith('-')) {
    errors.push('Leading or trailing hyphen: ' + text);
  }
  if (text.includes('--')) {
    errors.push('Double hyphen: ' + text);
  }
  return { valid: errors.length === 0, errors };
}

